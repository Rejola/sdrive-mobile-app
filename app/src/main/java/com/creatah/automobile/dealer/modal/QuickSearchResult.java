package com.creatah.automobile.dealer.modal;

public class QuickSearchResult {
    String spare_name;
    String spare_mrp;
    String spare_cgst;
    String spare_sgst;
    String labour_name;
    String labour_mrp;
    String labour_cgst;
    String labour_sgst;

    public QuickSearchResult(String spare_name, String spare_mrp, String spare_cgst, String spare_sgst, String labour_name, String labour_mrp, String labour_cgst, String labour_sgst) {
        this.spare_name = spare_name;
        this.spare_mrp = spare_mrp;
        this.spare_cgst = spare_cgst;
        this.spare_sgst = spare_sgst;
        this.labour_name = labour_name;
        this.labour_mrp = labour_mrp;
        this.labour_cgst = labour_cgst;
        this.labour_sgst = labour_sgst;
    }

    public String getSpare_name() {
        return spare_name;
    }

    public void setSpare_name(String spare_name) {
        this.spare_name = spare_name;
    }

    public String getSpare_mrp() {
        return spare_mrp;
    }

    public void setSpare_mrp(String spare_mrp) {
        this.spare_mrp = spare_mrp;
    }

    public String getSpare_cgst() {
        return spare_cgst;
    }

    public void setSpare_cgst(String spare_cgst) {
        this.spare_cgst = spare_cgst;
    }

    public String getSpare_sgst() {
        return spare_sgst;
    }

    public void setSpare_sgst(String spare_sgst) {
        this.spare_sgst = spare_sgst;
    }

    public String getLabour_name() {
        return labour_name;
    }

    public void setLabour_name(String labour_name) {
        this.labour_name = labour_name;
    }

    public String getLabour_mrp() {
        return labour_mrp;
    }

    public void setLabour_mrp(String labour_mrp) {
        this.labour_mrp = labour_mrp;
    }

    public String getLabour_cgst() {
        return labour_cgst;
    }

    public void setLabour_cgst(String labour_cgst) {
        this.labour_cgst = labour_cgst;
    }

    public String getLabour_sgst() {
        return labour_sgst;
    }

    public void setLabour_sgst(String labour_sgst) {
        this.labour_sgst = labour_sgst;
    }




}
